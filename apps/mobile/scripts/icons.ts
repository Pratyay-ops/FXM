/**
 * The Android launcher icons, the splash icon and the media notification's small icon, drawn
 * from the FXM mark. Edit this file, then run `scripts/run.sh pnpm --filter @fxm/mobile icons`
 * to rewrite the resources; icons.test.ts fails while the committed files differ from what this
 * module produces.
 */
import type { Image } from './png.ts'

type Rgb = readonly [number, number, number]
type Inside = (x: number, y: number) => boolean
type Paint = (x: number, y: number) => Rgb

/**
 * The FXM mark in its 32-unit grid: five rounded bars whose tops trace an "M" on a violet
 * tile. The same art as the web app's favicon (apps/web/index.html) and its LogoMark.
 */
export const MARK = {
  size: 32,
  tileRadius: 8,
  gradient: ['#8b5cf6', '#5b21b6'], // from the top-left to the bottom-right corner
  barWidth: 3.2,
  bars: [
    { x: 4.8, y: 15, height: 9 },
    { x: 9.6, y: 8, height: 16 },
    { x: 14.4, y: 13, height: 11 },
    { x: 19.2, y: 8, height: 16 },
    { x: 24, y: 15, height: 9 },
  ],
} as const

/** Where the mark's 32-unit grid lands on a canvas: canvas = offset + scale * mark. */
interface Placement {
  offset: number
  scale: number
}

/**
 * Adaptive icons are 108 units and the launcher's mask, which shapes the tile, hides the outer
 * 18. The mark's grid spans the visible 72 units, which keeps the bars in the 66-unit safe circle.
 */
const ADAPTIVE: Placement = { offset: 18, scale: 72 / MARK.size }
/** Android 12+ masks the splash icon to the middle two thirds: a 72-unit circle. */
const SPLASH_TILE: Placement = { offset: 26, scale: 56 / MARK.size }
/** Legacy (Android 7) icons are 48 units: a rounded square, or a circle for round icons. */
const LEGACY_TILE: Placement = { offset: 4, scale: 40 / MARK.size }
const LEGACY_ROUND: Placement = { offset: 2, scale: 44 / MARK.size }

/** Densities of the legacy PNG icons, as multiples of the 48 px mdpi size. */
export const LEGACY_DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 } as const

const XML_HEADER =
  '<?xml version="1.0" encoding="utf-8"?>\n' +
  '<!-- Generated by apps/mobile/scripts/icons.ts from the FXM mark: edit that file instead. -->\n'

function rgb(hex: string): Rgb {
  const value = Number.parseInt(hex.slice(1), 16)
  return [(value >> 16) & 255, (value >> 8) & 255, value & 255]
}

function num(value: number): string {
  return String(Number(value.toFixed(3)))
}

interface Box {
  x: number
  y: number
  width: number
  height: number
  radius: number
}

function tileBox({ offset, scale }: Placement): Box {
  const size = MARK.size * scale
  return { x: offset, y: offset, width: size, height: size, radius: MARK.tileRadius * scale }
}

function barBoxes({ offset, scale }: Placement): Box[] {
  return MARK.bars.map((bar) => ({
    x: offset + bar.x * scale,
    y: offset + bar.y * scale,
    width: MARK.barWidth * scale,
    height: bar.height * scale,
    radius: (MARK.barWidth / 2) * scale,
  }))
}

// --- Vector drawables (adaptive icon layers and the splash icon) ----------------------

function boxPath({ x, y, width, height, radius: r }: Box): string {
  const arc = (dx: number, dy: number) => `a${num(r)},${num(r)} 0 0 1 ${num(dx)},${num(dy)}`
  return (
    `M${num(x + r)},${num(y)}h${num(width - 2 * r)}${arc(r, r)}v${num(height - 2 * r)}` +
    `${arc(-r, r)}h${num(2 * r - width)}${arc(-r, -r)}v${num(2 * r - height)}${arc(r, -r)}z`
  )
}

function gradientPath(box: Box, from: Box): string {
  const [start, end] = MARK.gradient
  return [
    `    <path android:pathData="${boxPath(box)}">`,
    '        <aapt:attr name="android:fillColor">',
    '            <gradient',
    '                android:type="linear"',
    `                android:startX="${num(from.x)}"`,
    `                android:startY="${num(from.y)}"`,
    `                android:endX="${num(from.x + from.width)}"`,
    `                android:endY="${num(from.y + from.height)}"`,
    `                android:startColor="${start}"`,
    `                android:endColor="${end}" />`,
    '        </aapt:attr>',
    '    </path>',
  ].join('\n')
}

function barsPath(placement: Placement): string {
  const data = barBoxes(placement).map(boxPath).join('')
  return `    <path\n        android:fillColor="#ffffff"\n        android:pathData="${data}" />`
}

function vector(paths: string[], gradient: boolean): string {
  const namespaces = gradient ? '\n    xmlns:aapt="http://schemas.android.com/aapt"' : ''
  return (
    `${XML_HEADER}<vector xmlns:android="http://schemas.android.com/apk/res/android"${namespaces}\n` +
    '    android:width="108dp"\n    android:height="108dp"\n' +
    '    android:viewportWidth="108"\n    android:viewportHeight="108">\n' +
    `${paths.join('\n')}\n</vector>\n`
  )
}

const ADAPTIVE_ICON = `${XML_HEADER}<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
`

// --- Raster icons (Android 7 has no adaptive icons) -----------------------------------

const SAMPLES = 8 // per pixel and axis: 64 samples give smooth edges

function insideBox({ x, y, width, height, radius }: Box): Inside {
  const cx = x + width / 2
  const cy = y + height / 2
  const hx = width / 2 - radius
  const hy = height / 2 - radius
  return (px, py) => {
    const qx = Math.abs(px - cx) - hx
    const qy = Math.abs(py - cy) - hy
    const ox = Math.max(qx, 0)
    const oy = Math.max(qy, 0)
    return Math.sqrt(ox * ox + oy * oy) + Math.min(Math.max(qx, qy), 0) <= radius
  }
}

function insideCircle(cx: number, cy: number, radius: number): Inside {
  return (px, py) => (px - cx) * (px - cx) + (py - cy) * (py - cy) <= radius * radius
}

/** The mark's diagonal gradient across `from`, as in vector drawables and SVG. */
function linearGradient(from: Box): Paint {
  const start = rgb(MARK.gradient[0])
  const end = rgb(MARK.gradient[1])
  const length2 = from.width * from.width + from.height * from.height
  return (px, py) => {
    const along = (px - from.x) * from.width + (py - from.y) * from.height
    const t = Math.min(1, Math.max(0, along / length2))
    return [
      start[0] + (end[0] - start[0]) * t,
      start[1] + (end[1] - start[1]) * t,
      start[2] + (end[2] - start[2]) * t,
    ]
  }
}

interface Layer {
  inside: Inside
  paint: Paint
}

/** Rasterizes opaque layers (the last one on top) onto a transparent square image. */
function render(pixels: number, canvas: number, layers: Layer[]): Image {
  const unit = canvas / pixels
  const rgba = new Uint8Array(pixels * pixels * 4)
  for (let py = 0; py < pixels; py++) {
    for (let px = 0; px < pixels; px++) {
      let red = 0
      let green = 0
      let blue = 0
      let hits = 0
      for (let sy = 0; sy < SAMPLES; sy++) {
        for (let sx = 0; sx < SAMPLES; sx++) {
          const x = (px + (sx + 0.5) / SAMPLES) * unit
          const y = (py + (sy + 0.5) / SAMPLES) * unit
          const layer = layers.findLast((candidate) => candidate.inside(x, y))
          if (!layer) continue
          const [r, g, b] = layer.paint(x, y)
          red += r
          green += g
          blue += b
          hits++
        }
      }
      // Straight alpha: the average colour of the covered samples, and their share as alpha.
      const offset = (py * pixels + px) * 4
      if (hits > 0) {
        rgba[offset] = Math.round(red / hits)
        rgba[offset + 1] = Math.round(green / hits)
        rgba[offset + 2] = Math.round(blue / hits)
      }
      rgba[offset + 3] = Math.round((hits * 255) / (SAMPLES * SAMPLES))
    }
  }
  return { width: pixels, height: pixels, rgba }
}

function barsLayer(placement: Placement): Layer {
  const bars = barBoxes(placement).map(insideBox)
  return { inside: (x, y) => bars.some((inside) => inside(x, y)), paint: () => [255, 255, 255] }
}

function legacyIcon(pixels: number, round: boolean): Image {
  const placement = round ? LEGACY_ROUND : LEGACY_TILE
  const tile = tileBox(placement)
  const shape = round ? insideCircle(24, 24, tile.width / 2) : insideBox(tile)
  return render(pixels, 48, [{ inside: shape, paint: linearGradient(tile) }, barsLayer(placement)])
}

// --- The notification's small icon ------------------------------------------------------

/** Where the native player's notification icon goes, relative to apps/mobile/android. */
export const NOTIFICATION_ICON_PATH = 'fxm-player/src/main/res/drawable/fxm_notification_icon.xml'

/** Android's status-bar icons: a 24-unit grid whose outer 2 units stay empty. */
const STATUS_BAR = { size: 24, padding: 2 } as const

/**
 * The media notification's small icon (stage 6.3): the mark's five bars without the tile, white
 * on transparent, centred in the status bar's live area. Android draws only its alpha.
 */
export function notificationIcon(): string {
  const left = Math.min(...MARK.bars.map((bar) => bar.x))
  const right = Math.max(...MARK.bars.map((bar) => bar.x + MARK.barWidth))
  const top = Math.min(...MARK.bars.map((bar) => bar.y))
  const bottom = Math.max(...MARK.bars.map((bar) => bar.y + bar.height))
  const live = STATUS_BAR.size - 2 * STATUS_BAR.padding
  const scale = live / Math.max(right - left, bottom - top)
  const dx = (STATUS_BAR.size - (right - left) * scale) / 2 - left * scale
  const dy = (STATUS_BAR.size - (bottom - top) * scale) / 2 - top * scale
  const data = MARK.bars
    .map((bar) =>
      boxPath({
        x: dx + bar.x * scale,
        y: dy + bar.y * scale,
        width: MARK.barWidth * scale,
        height: bar.height * scale,
        radius: (MARK.barWidth / 2) * scale,
      }),
    )
    .join('')
  return (
    `${XML_HEADER}<vector xmlns:android="http://schemas.android.com/apk/res/android"\n` +
    `    android:width="${STATUS_BAR.size}dp"\n    android:height="${STATUS_BAR.size}dp"\n` +
    `    android:viewportWidth="${STATUS_BAR.size}"\n    android:viewportHeight="${STATUS_BAR.size}">\n` +
    `    <path\n        android:fillColor="#ffffff"\n        android:pathData="${data}" />\n</vector>\n`
  )
}

// --- Everything together ----------------------------------------------------------------

export interface AndroidResources {
  /** Text resources by path under android/app/src/main/res. */
  xml: Map<string, string>
  /** PNG resources by path under android/app/src/main/res. */
  png: Map<string, Image>
}

export function androidResources(): AndroidResources {
  const canvas: Box = { x: 0, y: 0, width: 108, height: 108, radius: 0 }
  const splashTile = tileBox(SPLASH_TILE)
  const xml = new Map<string, string>([
    // The gradient runs across the visible part, as across the favicon's tile.
    [
      'drawable/ic_launcher_background.xml',
      vector([gradientPath(canvas, tileBox(ADAPTIVE))], true),
    ],
    ['drawable/ic_launcher_foreground.xml', vector([barsPath(ADAPTIVE)], false)],
    [
      'drawable/splash_icon.xml',
      vector([gradientPath(splashTile, splashTile), barsPath(SPLASH_TILE)], true),
    ],
    ['mipmap-anydpi-v26/ic_launcher.xml', ADAPTIVE_ICON],
    ['mipmap-anydpi-v26/ic_launcher_round.xml', ADAPTIVE_ICON],
  ])
  const png = new Map<string, Image>()
  for (const [density, factor] of Object.entries(LEGACY_DENSITIES)) {
    png.set(`mipmap-${density}/ic_launcher.png`, legacyIcon(48 * factor, false))
    png.set(`mipmap-${density}/ic_launcher_round.png`, legacyIcon(48 * factor, true))
  }
  return { xml, png }
}
