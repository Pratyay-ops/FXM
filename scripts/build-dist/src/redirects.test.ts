import { describe, expect, it } from 'vitest'
import { EMBED_KINDS, embedPath } from '../../../apps/web/src/embed/target.ts'
import { formatId } from '../../../packages/core/src/index.ts'
import {
  EMBED_ROUTE_KINDS,
  matchRedirect,
  parseRedirects,
  redirectProblems,
  redirectRules,
  serializeRedirects,
} from './redirects.ts'

/** What make dist composes for the embed: its page, the 404 copy and its assets. */
const EMBED_FILES = [
  'index.html',
  'embed/index.html',
  'embed/404.html',
  'embed/assets/index-rNFl62ek.js',
  'embed/assets/index.css',
  'app/index.html',
  'app/404.html',
  'app/assets/index.js',
]

describe("the embed's rewrites", () => {
  it('cover every kind of player the embed’s router knows', () => {
    expect([...EMBED_ROUTE_KINDS]).toEqual([...EMBED_KINDS])
  })

  it('rewrite each route to the embed’s folder, once the embed is composed', () => {
    expect(redirectRules(EMBED_FILES)).toEqual([
      { from: '/embed/track/*', to: '/embed/', status: 200 },
      { from: '/embed/album/*', to: '/embed/', status: 200 },
      { from: '/embed/playlist/*', to: '/embed/', status: 200 },
    ])
    expect(redirectRules(EMBED_FILES.filter((file) => !file.startsWith('embed/')))).toEqual([])
  })

  it('answer every address the share dialog builds, the encoded ones too', () => {
    const rules = redirectRules(EMBED_FILES)
    const addresses = EMBED_KINDS.flatMap((kind) =>
      [
        formatId('ytm', kind, 'MPREb_abc'),
        formatId('yt', kind, 'dQw4w9WgXcQ'),
        formatId('archive', kind, 'item/song.flac'),
      ].map((id) => embedPath({ kind, id } as Parameters<typeof embedPath>[0])),
    )
    expect(addresses).toContain('/embed/track/archive:item%2Fsong.flac')
    for (const path of [...addresses, '/embed/album/ytm:MPREb_abc/']) {
      expect(matchRedirect(rules, path), path).toBeDefined()
    }
  })

  it('leave the embed’s own files, its folder and every other path alone', () => {
    const rules = redirectRules(EMBED_FILES)
    for (const path of [
      '/embed/',
      '/embed',
      '/embed/assets/index-rNFl62ek.js',
      '/embed/assets/index.css',
      '/embed/track',
      '/embed/tracks/ytm:abc',
      '/embed/artist/ytm:abc',
      '/app/track/ytm:abc',
      '/%65mbed/track/ytm:abc',
    ]) {
      expect(matchRedirect(rules, path), path).toBeUndefined()
    }
    expect(redirectProblems(rules, EMBED_FILES)).toEqual([])
  })

  it('refuse a rule that hides a file, points at no folder page, or isn’t a 200 rewrite', () => {
    expect(
      redirectProblems(
        [
          { from: '/embed/*', to: '/embed/', status: 200 },
          { from: '/embed/track/*', to: '/embed/index.html', status: 200 },
          { from: '/embed/:kind/*', to: '/embed/', status: 200 },
          { from: '/embed/album/*', to: '/nowhere/', status: 301 as 200 },
        ],
        EMBED_FILES,
      ),
    ).toEqual([
      '/embed/* would answer /embed/ instead of embed/index.html: rules win over files',
      '/embed/* would answer /embed/index.html instead of embed/index.html: rules win over files',
      '/embed/* would answer /embed/404 instead of embed/404.html: rules win over files',
      '/embed/* would answer /embed/404.html instead of embed/404.html: rules win over files',
      '/embed/* would answer /embed/assets/index-rNFl62ek.js instead of embed/assets/index-rNFl62ek.js: rules win over files',
      '/embed/* would answer /embed/assets/index.css instead of embed/assets/index.css: rules win over files',
      '/embed/track/*: /embed/index.html is not a folder whose index.html Pages serves, so the rewrite would answer with a redirect or a 404',
      "/embed/:kind/*: a rule's path is literal and ends in /* (a folder's rest)",
      "/embed/album/*: FXM's rules are 200 rewrites only",
      '/embed/album/*: /nowhere/ is not a folder whose index.html Pages serves, so the rewrite would answer with a redirect or a 404',
    ])
  })

  it('read back as written, comments aside', () => {
    const rules = redirectRules(EMBED_FILES)
    const text = serializeRedirects(rules, ['Generated by make dist.'])
    expect(text).toBe(
      '# Generated by make dist.\n/embed/track/* /embed/ 200\n/embed/album/* /embed/ 200\n/embed/playlist/* /embed/ 200\n',
    )
    expect(parseRedirects(text)).toEqual({ rules, invalid: [] })
    expect(parseRedirects('/a /b 301\n/c\n').invalid).toEqual([
      'line 1: "/a /b 301" is not a 200 rewrite (from to 200)',
      'line 2: "/c" is not a 200 rewrite (from to 200)',
    ])
  })
})
