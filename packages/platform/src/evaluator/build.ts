/**
 * Builds the evaluator document, `apps/web/sandbox/eval.html`: one HTML file whose only script is
 * inline, so that the same file serves every platform:
 *
 * - the web deployment publishes it at `/sandbox/eval.html` with {@link evaluatorHeaderPolicy} as
 *   its `Content-Security-Policy` header (stage 2.8's `_headers`);
 * - the desktop app embeds it and serves it from its `fxm-eval:` scheme with that policy;
 * - the Android app loads it into its evaluator WebView, where its `<meta>` policy applies.
 *
 * The script is allowed by its SHA-256 hash, never by `'unsafe-inline'`. Its `<meta>` policy
 * repeats everything of the header policy that a `<meta>` element can carry (`sandbox` cannot be
 * set that way), so the document allows no connections however it is loaded.
 *
 * Run `scripts/run.sh pnpm --filter @fxm/platform build:evaluator` after changing anything the
 * document's script imports; `build.test.ts` fails while the committed file is out of date.
 *
 * @module
 */

/** The evaluator document, relative to the repository's root. */
export const EVALUATOR_DOCUMENT_FILE = 'apps/web/sandbox/eval.html'

/**
 * The Android plugin's pin of the document, relative to the repository's root: the plugin loads
 * only a document with this SHA-256 into its WebView.
 */
export const EVALUATOR_ANDROID_PIN_FILE =
  'apps/mobile/android/app/src/main/java/io/github/pratyayops/fxm/evaluator/EvaluatorDocument.java'

/** A built evaluator document. */
export interface EvaluatorDocumentBuild {
  /** The whole HTML file. */
  readonly html: string
  /** The inline script, exactly as it appears in the file. */
  readonly script: string
  /** The script's CSP hash source, e.g. `'sha256-…'`. */
  readonly scriptHash: string
  /** The `<meta>` policy in the file. */
  readonly metaPolicy: string
  /** The policy to serve the file with: the `<meta>` one, after `sandbox allow-scripts`. */
  readonly headerPolicy: string
}

/**
 * The SHA-256 of the document's UTF-8 text with LF line endings, as lowercase hexadecimal: what
 * the Android plugin compares the document it is handed with.
 */
export async function documentSha256(html: string): Promise<string> {
  const text = html.replaceAll('\r\n', '\n')
  const digest = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text))
  return Array.from(new Uint8Array(digest), (byte) => byte.toString(16).padStart(2, '0')).join('')
}

/** The Java source of the Android plugin's pin of the document with `sha256`. */
export function renderAndroidPin(sha256: string): string {
  return [
    '// Generated by packages/platform/src/evaluator/build.ts (pnpm --filter @fxm/platform',
    '// build:evaluator): do not edit.',
    'package io.github.pratyayops.fxm.evaluator;',
    '',
    '/** The evaluator document this app was built with: the SHA-256 of apps/web/sandbox/eval.html. */',
    'final class EvaluatorDocument {',
    '',
    "    /** Lowercase hexadecimal, of the file's UTF-8 text with LF line endings. */",
    `    static final String SHA256 = "${sha256}";`,
    '',
    '    private EvaluatorDocument() {}',
    '}',
    '',
  ].join('\n')
}

/** The CSP hash source of a script: `'sha256-<base64 of its UTF-8 SHA-256>'`. */
export async function scriptHashOf(script: string): Promise<string> {
  const digest = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(script))
  return `'sha256-${btoa(String.fromCharCode(...new Uint8Array(digest)))}'`
}

/**
 * The document's `<meta>` policy: nothing may load or connect, and only the inline script with
 * `hash` runs, with `'unsafe-eval'` for the scripts it compiles and `'wasm-unsafe-eval'` for any
 * WebAssembly they need.
 */
export function evaluatorMetaPolicy(hash: string): string {
  return [
    "default-src 'none'",
    `script-src ${hash} 'unsafe-eval' 'wasm-unsafe-eval'`,
    "connect-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join('; ')
}

/**
 * The policy the document is served with, as stage 2.8's `_headers` rule for
 * `/sandbox/eval.html` (and the desktop app's scheme handler) sets it: `sandbox allow-scripts`,
 * which makes the document's origin opaque however it is loaded, then the `<meta>` policy.
 */
export function evaluatorHeaderPolicy(hash: string): string {
  return `sandbox allow-scripts; ${evaluatorMetaPolicy(hash)}`
}

/** Wraps the bundled script into the document. */
export async function renderEvaluatorDocument(script: string): Promise<EvaluatorDocumentBuild> {
  if (/<\/script/iu.test(script)) {
    throw new Error('The evaluator script contains </script, which would end the inline script')
  }
  const scriptHash = await scriptHashOf(script)
  const metaPolicy = evaluatorMetaPolicy(scriptHash)
  const html = [
    '<!doctype html>',
    "<!-- Generated by packages/platform/src/evaluator/build.ts: do not edit. FXM's isolated",
    '     evaluator (packages/platform/src/evaluator/README.md). The script bundles bgutils-js',
    '     (MIT, Copyright (c) LuanRT). -->',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    `<meta http-equiv="Content-Security-Policy" content="${metaPolicy}">`,
    '<meta name="referrer" content="no-referrer">',
    '<title>FXM evaluator</title>',
    '</head>',
    '<body>',
    `<script>${script}</script>`,
    '</body>',
    '</html>',
    '',
  ].join('\n')
  return {
    html,
    script,
    scriptHash,
    metaPolicy,
    headerPolicy: evaluatorHeaderPolicy(scriptHash),
  }
}

/**
 * The first line of the script: Biome lints scripts inside HTML, and a bundle (bgutils-js
 * included) is not code to lint.
 */
export const LINT_SUPPRESSION =
  '// biome-ignore-all lint: a generated bundle (packages/platform/src/evaluator/build.ts)'

/**
 * Bundles the document's script, `document-entry.ts` and what it imports (bgutils-js included),
 * into one classic script for browsers, without comments other than its first line,
 * {@link LINT_SUPPRESSION}, and the bundler's module markers.
 */
export async function bundleEvaluatorScript(): Promise<string> {
  const { build } = await import('rolldown')
  const path = (relative: string) => decodeURIComponent(new URL(relative, import.meta.url).pathname)
  const result = await build({
    input: path('./document-entry.ts'),
    // The package's root, so the module names in the output are the same wherever it runs.
    cwd: path('../..'),
    write: false,
    platform: 'browser',
    logLevel: 'warn',
    output: { format: 'iife', comments: false, minify: false },
  })
  const [chunk] = result.output
  if (chunk === undefined || chunk.type !== 'chunk') throw new Error('The bundle is empty')
  return `${LINT_SUPPRESSION}\n${chunk.code.trim()}`
}

/** Bundles and renders the evaluator document. */
export async function buildEvaluatorDocument(): Promise<EvaluatorDocumentBuild> {
  return renderEvaluatorDocument(await bundleEvaluatorScript())
}
